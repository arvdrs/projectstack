def _missing(ctx: Context, plan: Plan | None) -> list[Finding]:
    rows = _q(ctx, f"""
        SELECT label, extract(failure_message, '{MARKER}: ([A-Za-z0-9_.,-]+)') AS vars,
               position(url, 'NOT_FOUND') > 0 AS in_url, count() AS n,
               toUnixTimestamp64Milli(min(ts)) AS first_ms, toUnixTimestamp64Milli(max(ts)) AS last_ms
        FROM {{db}}.samples
        WHERE run_id = {{{{run:String}}}} AND (position(failure_message, '{MARKER}') > 0 OR position(url, 'NOT_FOUND') > 0)
        GROUP BY label, vars, in_url ORDER BY n DESC""")
    if not rows:
        return []
    by_label: dict[str, dict[str, Any]] = {}
    named: set[str] = set()
    for r in rows:
        e = by_label.setdefault(r["label"], {"label": r["label"], "samples": 0, "vars": set(), "first_ms": r["first_ms"],
                                             "last_ms": r["last_ms"], "in_url": False})
        e["samples"] += int(r["n"])
        e["first_ms"], e["last_ms"] = min(e["first_ms"], r["first_ms"]), max(e["last_ms"], r["last_ms"])
        e["in_url"] = e["in_url"] or bool(r["in_url"])
        vs = {v for v in (r["vars"] or "").split(",") if v and v != "NOT_FOUND"}
        e["vars"] |= vs
        named |= vs
    items = sorted(by_label.values(), key=lambda e: -e["samples"])
    total = sum(e["samples"] for e in items)
    if total < 1:
        return []
    mapping = _mapping(ctx, plan, [e["label"] for e in items], only=named or None)
    vars_named = sorted(named) or sorted(m["var"] for m in mapping)
    what = ", ".join(vars_named[:4]) if vars_named else "a correlated value"
    title = (f"Correlation: {what} {'was' if len(vars_named) <= 1 else 'were'} missing in {len(items)} "
             f"request{'s' if len(items) > 1 else ''} ({total:,} samples sent NOT_FOUND)")
    detail = ("An extractor returned its default value NOT_FOUND and later requests sent it. "
              + (" ".join(_fix_missing(m) for m in mapping[:3]) if mapping else
                 "Pass the test plan (--jmx) to see which extractor sets each value."))
    return [_finding("missing_value", "critical", title, detail, items, ctx, {
        "samples": total, "variables": vars_named,
        "labels": [{"label": e["label"], "samples": e["samples"], "variables": sorted(e["vars"]),
                    "in_url": e["in_url"], "first_offset_s": _offset(ctx, e["first_ms"])} for e in items[:10]],
        "mapping": mapping[:6], "fixes": [_fix_missing(m) for m in mapping[:6]]})]


def _auth_onset(ctx: Context, plan: Plan | None) -> list[Finding]:
    rows = _q(ctx, """
        SELECT label, toUnixTimestamp(toStartOfMinute(ts)) * 1000 AS m, count() AS n,
               countIf(response_code IN ('401', '403')) AS bad
        FROM {db}.samples WHERE run_id = {{run:String}} AND kind != 'transaction'
          AND label IN (SELECT DISTINCT label FROM {db}.samples
                        WHERE run_id = {{run:String}} AND response_code IN ('401', '403'))
        GROUP BY label, m ORDER BY label, m""")
    series: dict[str, list[dict]] = {}
    for r in rows:
        series.setdefault(r["label"], []).append(r)
    onset, always = [], []
    for label, pts in series.items():
        bad = sum(int(p["bad"]) for p in pts)
        if bad < MIN_SAMPLES:
            continue
        first_bad = next((i for i, p in enumerate(pts) if p["bad"] / p["n"] >= 0.5), None)
        if first_bad is None:
            continue
        item = {"label": label, "samples": bad, "share_pct": round(bad * 100 / sum(int(p["n"]) for p in pts), 1),
                "first_ms": int(pts[first_bad]["m"]), "last_ms": int(pts[-1]["m"]) + 60_000}
        healthy_before = any(p["bad"] / p["n"] < 0.05 for p in pts[:first_bad])
        (onset if healthy_before else always).append(item)
    out = []
    if onset:
        onset.sort(key=lambda e: e["first_ms"])
        at = _offset(ctx, onset[0]["first_ms"])
        mapping = _mapping(ctx, plan, [e["label"] for e in onset], tokenish=True)
        fix = ("Requests were accepted at first and rejected later — the pattern of a token or session that expires "
               f"(here after about {round(at / 60)} minutes). ")
        if mapping:
            m = mapping[0]
            fix += (f"{m['var']} is set by {m['extractors'][0]['description']}: if that runs once per user (login "
                    "outside the loop), extract it again each iteration or add a token refresh before it expires.")
        else:
            fix += ("Extract the token or session again each iteration (or add a refresh step) instead of "
                    "reusing the one from the first login." + ("" if plan else " Pass --jmx to see which extractor sets it."))
        out.append(_finding("auth_onset", "critical",
                            f"401/403 responses began at {offset(at)} for {len(onset)} request"
                            f"{'s' if len(onset) > 1 else ''} after they had been succeeding",
                            fix, onset, ctx, {"samples": sum(e["samples"] for e in onset), "onset_offset_s": at,
                                              "labels": _label_items(ctx, onset), "mapping": mapping[:6]}))
    if always:
        mapping = _mapping(ctx, plan, [e["label"] for e in always], tokenish=True)
        fix = "These requests were rejected from their first minute, so the credential they send is never valid. "
        if mapping:
            m = mapping[0]
            fix += (f"Check that {m['var']} ({m['extractors'][0]['description']}) is extracted and sent in the "
                    "expected header and format (for example Authorization: Bearer ${…}).")
        else:
            fix += ("A recorded token or session ID may be hard-coded in the script and has expired: correlate it."
                    + ("" if plan else " Pass --jmx to see which variables these requests send."))
        out.append(_finding("auth_always", "critical",
                            f"{len(always)} request{'s' if len(always) > 1 else ''} failed with 401/403 from the start",
                            fix, always, ctx, {"samples": sum(e["samples"] for e in always),
                                               "labels": _label_items(ctx, always), "mapping": mapping[:6]}))
    return out


def _label_items(ctx: Context, items: list[dict]) -> list[dict]:
    return [{"label": e["label"], "samples": e["samples"], "share_pct": e.get("share_pct"),
             "first_offset_s": _offset(ctx, e["first_ms"])} for e in items[:10]]


def _login_redirect(ctx: Context, plan: Plan | None) -> list[Finding]:
    rows = _q(ctx, f"""
        SELECT replaceRegexpOne(label, '-[0-9]+$', '') AS label, count() AS samples, any(url) AS example_url,
               toUnixTimestamp64Milli(min(ts)) AS first_ms, toUnixTimestamp64Milli(max(ts)) AS last_ms
        FROM {{db}}.samples
        WHERE run_id = {{{{run:String}}}} AND kind != 'transaction'
          AND match(url, '{_LOGIN_URL}') AND NOT match(label, '{_LOGIN_LABEL}')
        GROUP BY label HAVING samples >= {MIN_SAMPLES} ORDER BY samples DESC""")
    if not rows:
        return []
    mapping = _mapping(ctx, plan, [r["label"] for r in rows], tokenish=True)
    fix = ("The server sent these requests to its login page, so it did not recognise the session. Check that the "
           "HTTP Cookie Manager is in the plan and that the session ID is correlated")
    fix += (f" — {mapping[0]['var']} is set by {mapping[0]['extractors'][0]['description']}." if mapping else ".")
    return [_finding("login_redirect", "critical" if len(rows) > 1 else "warning",
                     f"{len(rows)} request{'s were' if len(rows) > 1 else ' was'} redirected to a login page",
                     fix, rows, ctx, {"samples": sum(int(r["samples"]) for r in rows),
                                      "labels": [{"label": r["label"], "samples": int(r["samples"]),
                                                  "example_url": r["example_url"][:200],
                                                  "first_offset_s": _offset(ctx, r["first_ms"])} for r in rows[:10]],
                                      "mapping": mapping[:6]})]


def _auth_messages(ctx: Context, plan: Plan | None) -> list[Finding]:
    rows = _q(ctx, f"""
        SELECT label, count() AS samples, any(response_code) AS code,
               any(if(failure_message != '', failure_message, response_message)) AS message,
               toUnixTimestamp64Milli(min(ts)) AS first_ms, toUnixTimestamp64Milli(max(ts)) AS last_ms
        FROM {{db}}.samples
        WHERE run_id = {{{{run:String}}}} AND NOT success AND response_code NOT IN ('401', '403')
          AND position(failure_message, '{MARKER}') = 0
          AND match(concat(response_message, ' ', failure_message), '{_AUTH_MSG}')
        GROUP BY label HAVING samples >= {MIN_SAMPLES} ORDER BY samples DESC""")
    if not rows:
        return []
    mapping = _mapping(ctx, plan, [r["label"] for r in rows], tokenish=True)
    fix = (f"Failures such as “{str(rows[0]['message'])[:120]}” point to a session or token the server no longer "
           "accepts. ")
    fix += (f"Check {mapping[0]['var']}, set by {mapping[0]['extractors'][0]['description']}." if mapping else
            "Check how the session or token is extracted and refreshed.")
    return [_finding("auth_message", "warning",
                     f"{len(rows)} request{'s' if len(rows) > 1 else ''} failed with authentication-related messages",
                     fix, rows, ctx, {"samples": sum(int(r["samples"]) for r in rows),
                                      "labels": [{"label": r["label"], "samples": int(r["samples"]), "code": r["code"],
                                                  "message": str(r["message"])[:200],
                                                  "first_offset_s": _offset(ctx, r["first_ms"])} for r in rows[:10]],
                                      "mapping": mapping[:6]})]
