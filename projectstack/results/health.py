"""
Correlation health check: signs in a run that dynamic values were not handled.

Patterns, each found with one query over the run's samples:

  missing_value   a request sent an extractor's default (NOT_FOUND): scripts generated by ProjectStack
                  fail such samples with "PS_CORRELATION_MISSING: <var>"; in any script, NOT_FOUND
                  inside the request URL gives it away
  auth_onset      401/403 responses that start after the label had been succeeding (a token or
                  session that expires), or that fail it from its first minute (never valid)
  login_redirect  requests (or their redirect hops) that land on a login page
  auth_message    failures whose message reads like an authentication problem ("session expired",
                  "invalid token", "CSRF" …) without a 401/403

With the test plan (--jmx), each finding names the variables the failing requests
send, the extractor that sets each one and the sampler it sits on, and whether
that sampler itself was failing, and suggests a fix.
"""

from __future__ import annotations

import re
from typing import Any

from projectstack.results.detectors import Context, Finding
from projectstack.results.fmt import offset
from projectstack.results.plan import Plan

MARKER = "PS_CORRELATION_MISSING"
MIN_SAMPLES = 5
_LOGIN_URL = r"(?i)/(login|log-in|signin|sign-in|logon|auth/|authorize|sso|oauth|cas/|session/new|account/login)"
_LOGIN_LABEL = r"(?i)login|log-in|signin|sign-in|logon|auth|sso|oauth"
_AUTH_MSG = (r"(?i)invalid[ _-]?token|token[ _-]?(expired|invalid)|expired[ _-]?token|session[ _-]?(expired|timeout|"
             r"invalid)|invalid[ _-]?session|not[ _-]?logged[ _-]?in|csrf|xsrf|jwt|access[ _-]?denied")
_TOKENISH = re.compile(r"(?i)token|jwt|bearer|auth|session|sid|csrf|xsrf|cookie")


def check_run(db, run_id: str, plan: Plan | None = None) -> list[Finding]:
    """The health check on its own, for an analysed run (`pstack health`)."""
    from projectstack.results.detectors import Thresholds
    from projectstack.results.metrics import run_bounds
    ctx = Context(db=db, run_id=run_id, bounds=run_bounds(db, run_id), kinds={}, metrics={}, steady={}, columns=[],
                  sla=None, thresholds=Thresholds(), extra={"plan": plan} if plan else {})
    return detect(ctx)[0]


def detect(ctx: Context) -> tuple[list[Finding], str | None]:
    plan: Plan | None = ctx.extra.get("plan")
    findings = _missing(ctx, plan) + _auth_onset(ctx, plan) + _login_redirect(ctx, plan) + _auth_messages(ctx, plan)
    return findings, None


# ---------------------------------------------------------------------------

def _q(ctx: Context, sql: str, **params: Any) -> list[dict]:
    return ctx.db.dicts(sql.format(db=ctx.db.db), {"run": ctx.run_id, **params})


def _offset(ctx: Context, ms: int) -> int:
    return round((ms - ctx.bounds["start_ms"]) / 1000)


def _source_errors(ctx: Context, labels: set[str]) -> dict[str, float]:
    if not labels:
        return {}
    rows = _q(ctx, "SELECT label, round(countIf(NOT success) * 100 / count(), 2) AS err FROM {db}.samples "
                   "WHERE run_id = {{run:String}} AND has({{labels:Array(String)}}, label) GROUP BY label",
              labels=sorted(labels))
    return {r["label"]: float(r["err"]) for r in rows}


def _mapping(ctx: Context, plan: Plan | None, labels: list[str], only: set[str] | None = None,
             tokenish: bool = False) -> list[dict[str, Any]]:
    """For the failing labels: each correlated variable they send, its extractor(s) and their sampler's health."""
    if plan is None:
        return []
    seen: dict[str, dict[str, Any]] = {}
    for label in labels:
        for var in sorted(plan.vars_sent(label)):
            if only is not None and var not in only:
                continue
            if tokenish and not _TOKENISH.search(var) and not any(_TOKENISH.search(e.expression)
                                                                  for e in plan.extractors[var]):
                continue
            entry = seen.setdefault(var, {"var": var, "used_by": [], "extractors": [
                {"name": e.name, "kind": e.kind, "expression": e.expression, "source": e.source,
                 "default": e.default, "description": e.describe()} for e in plan.extractors[var]]})
            entry["used_by"].append(label)
    errors = _source_errors(ctx, {x["source"] for m in seen.values() for x in m["extractors"]})
    for m in seen.values():
        for x in m["extractors"]:
            x["source_error_pct"] = errors.get(x["source"])
    return list(seen.values())


def _fix_missing(m: dict[str, Any]) -> str:
    x = m["extractors"][0]
    if (x.get("source_error_pct") or 0) >= 5:
        return (f"{m['var']} comes from “{x['source']}”, which itself failed {x['source_error_pct']:g}% of the time — "
                "fix that request first; its error responses do not contain the value.")
    return (f"{x['description']} found no match, so {m['var']} kept its default {x['default'] or 'value'}. Check the "
            f"expression against the current response of “{x['source']}”: the value may have moved (body ↔ header), "
            "been renamed, or now come from a different request.")


def _finding(type_: str, severity: str, title: str, detail: str, rows: list[dict], ctx: Context,
             evidence: dict[str, Any]) -> Finding:
    starts = [r["first_ms"] for r in rows if r.get("first_ms")]
    ends = [r["last_ms"] for r in rows if r.get("last_ms")]
    return Finding(type="correlation", severity=severity, title=title, detail=detail,
                   start_ms=min(starts) if starts else None, end_ms=max(ends) if ends else None,
                   labels=[r["label"] for r in rows][:10], evidence={"pattern": type_, **evidence})


