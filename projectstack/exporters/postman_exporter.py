"""
Postman Collection v2.1 exporter.

Converts a list of HarRequest objects into a Postman Collection JSON
that can be imported directly into Postman.
"""

import json
from pathlib import Path
from urllib.parse import urlparse, parse_qs

from projectstack.parser.har_parser import HarRequest


# Headers that add noise in Postman collections
_SKIP_HEADERS = {
    "content-length", "host", "connection", "accept-encoding",
    "accept-language", "sec-fetch-dest", "sec-fetch-mode",
    "sec-fetch-site", "sec-ch-ua", "sec-ch-ua-mobile", "sec-ch-ua-platform",
    "upgrade-insecure-requests",
}


def _build_url(req: HarRequest) -> dict:
    parsed = urlparse(req.url)
    host_parts = (parsed.hostname or "").split(".")
    path_parts = [p for p in (parsed.path or "/").split("/") if p]

    url: dict = {
        "raw": req.url,
        "protocol": parsed.scheme,
        "host": host_parts,
        "path": path_parts,
    }

    if parsed.port:
        url["port"] = str(parsed.port)

    # Query parameters
    if req.query_params:
        url["query"] = [
            {"key": qp.get("name", ""), "value": qp.get("value", "")}
            for qp in req.query_params
        ]
    elif parsed.query:
        url["query"] = [
            {"key": k, "value": v[0] if v else ""}
            for k, v in parse_qs(parsed.query).items()
        ]

    return url


def _build_body(req: HarRequest) -> dict | None:
    if not req.body:
        return None

    mime = (req.body_mime_type or "").lower()

    if "json" in mime:
        return {
            "mode": "raw",
            "raw": req.body,
            "options": {"raw": {"language": "json"}},
        }
    if "form" in mime:
        # Try to parse as key=value pairs
        pairs = []
        for part in req.body.split("&"):
            if "=" in part:
                k, _, v = part.partition("=")
                pairs.append({"key": k, "value": v})
        return {"mode": "urlencoded", "urlencoded": pairs}

    return {"mode": "raw", "raw": req.body}


def _make_item(index: int, req: HarRequest) -> dict:
    parsed = urlparse(req.url)
    name = f"{req.method} {parsed.path or '/'}"

    headers = [
        {"key": k, "value": v}
        for k, v in req.headers.items()
        if k.lower() not in _SKIP_HEADERS
    ]

    request: dict = {
        "method": req.method,
        "header": headers,
        "url": _build_url(req),
    }

    body = _build_body(req)
    if body:
        request["body"] = body

    return {"name": name, "request": request, "response": []}


def export_postman(
    requests: list[HarRequest],
    output_path: str | Path,
    collection_name: str = "ProjectStack Collection",
) -> None:
    """
    Write a Postman Collection v2.1 JSON file.

    Args:
        requests:        Parsed HAR requests.
        output_path:     Where to write the .json file.
        collection_name: Name shown in Postman.
    """
    collection = {
        "info": {
            "name": collection_name,
            "description": "Generated by ProjectStack from HAR file",
            "schema": "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
        },
        "item": [_make_item(i, req) for i, req in enumerate(requests)],
        "variable": [],
    }
    Path(output_path).write_text(
        json.dumps(collection, indent=2), encoding="utf-8"
    )
