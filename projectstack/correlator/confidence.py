"""
Correlation confidence scorer.

Assigns a 0-100 score and a label (High / Medium / Low) to each
CorrelatedValue based on how likely it is to be a real dynamic value
that needs parameterisation.
"""

import math
import re
from projectstack.correlator.engine import CorrelatedValue


# Key names that strongly suggest a dynamic value
_TOKEN_KEYWORDS = re.compile(
    r"token|secret|key|auth|session|bearer|jwt|access|refresh|csrf|nonce|otp",
    re.IGNORECASE,
)
_ID_KEYWORDS = re.compile(r"id$|_id|uuid|guid", re.IGNORECASE)


def _entropy(value: str) -> float:
    """Shannon entropy of a string — higher means more random-looking."""
    if not value:
        return 0.0
    freq = {}
    for ch in value:
        freq[ch] = freq.get(ch, 0) + 1
    n = len(value)
    return -sum((c / n) * math.log2(c / n) for c in freq.values())


# Base score per detection pass (prefix match, first match wins)
_BASE_SCORES = (
    ("pass1_bearer", 88),
    ("pass1_jwt_claim", 72),
    ("pass1_jwt", 85),
    ("pass_rule", 86),
    ("pass_replay", 84),
    ("pass_html", 78),
    ("pass3_cookie_header", 80),
    ("pass3_redirect", 76),
    ("pass_comparison", 75),
    ("pass3_header", 70),
    ("pass3_cookie", 62),
    ("pass_url_id", 70),
    ("pass2_json", 65),
    ("pass_client", 68),
    ("pass_request_scan", 62),
    ("pass4_text", 55),
    ("pass6_", 70),
    ("custom_rule", 90),
)


def score(cv: CorrelatedValue) -> int:
    """
    Return a confidence score 0-100 for a CorrelatedValue.

    Scoring breakdown:
      Base score from detection pass        (50-90)
      +bonus for token/auth key name        (up to +10)
      +bonus for high-entropy value         (up to +8)
      +bonus for number of uses             (up to +10)
      +bonus for known patterns (JWT, UUID) (up to +5)
      +bonus when confirmed dynamic         (+15)
      -penalty for short numeric values     (-10)
      -penalty when both recordings had the same value (-35, or -10 for tokens)
    """
    # --- Base score by detection pass ---
    # detection_pass can be compound ("pass2_json,confirmed_dynamic") and AI passes
    # are named per provider ("pass6_groq"), so match on the first segment's prefix.
    passes = (cv.detection_pass or "").split(",")
    primary = passes[0]
    base = 50
    for prefix, pts in _BASE_SCORES:
        if primary.startswith(prefix):
            base = pts
            break

    bonus = 0

    # Bonus: key name suggests a token or secret
    if _TOKEN_KEYWORDS.search(cv.extract_key):
        bonus += 10
    elif _ID_KEYWORDS.search(cv.extract_key):
        bonus += 5

    # Bonus: high-entropy value (random-looking)
    ent = _entropy(cv.extract_value)
    if ent > 4.5:
        bonus += 8
    elif ent > 3.5:
        bonus += 4

    # Bonus: used in multiple subsequent requests
    uses = len(cv.used_in_requests)
    bonus += min(uses * 3, 10)

    # Bonus: looks like a UUID
    if re.fullmatch(
        r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}",
        cv.extract_value,
        re.IGNORECASE,
    ):
        bonus += 5

    # Bonus: proven dynamic by comparing two recordings or by a replay
    if "confirmed_dynamic" in passes or "replay_verified" in passes:
        bonus += 15

    # Penalty: short numeric values are easy to mis-match
    if re.fullmatch(r"\d{1,5}", cv.extract_value or ""):
        bonus -= 10

    # Penalty: the second recording had exactly the same value
    if "static_in_both" in passes:
        bonus -= 35
    elif "same_in_both" in passes:
        bonus -= 10

    return max(1, min(base + bonus, 99))


def label(score_val: int) -> str:
    if score_val >= 75:
        return "High"
    if score_val >= 50:
        return "Medium"
    return "Low"


def annotate(correlated_values: list[CorrelatedValue]) -> list[dict]:
    """
    Return a list of dicts, each containing the CorrelatedValue plus
    'confidence_score' and 'confidence_label' keys.
    """
    result = []
    for cv in correlated_values:
        s = score(cv)
        result.append({
            "value": cv,
            "confidence_score": s,
            "confidence_label": label(s),
        })
    return result


# ---------------------------------------------------------------------------
# Overall confidence in an auto-correlation result
# ---------------------------------------------------------------------------

def _untraced_values(correlated: list[CorrelatedValue], requests: list) -> list[tuple[int, str, str]]:
    """
    Values requests send that look dynamic, are not correlated, and appear in no
    earlier response: (request index, location, value). If they change per
    session — generated by JavaScript, or returned by a request that was
    filtered out — the script sends stale copies.
    """
    from projectstack.correlator.engine import _is_dynamic, _is_route_segment
    from projectstack.correlator.matching import contains_value, request_values

    covered = {cv.extract_value for cv in correlated if cv.extract_value}
    out, seen = [], set()
    for k, req in enumerate(requests):
        for loc, value in request_values(req):
            key = loc.split(":", 1)[-1]
            if value in covered or value in seen or not _is_dynamic(value, key):
                continue
            if loc == "path" and _is_route_segment(value):
                continue
            if any(value in c or c in value for c in covered if len(c) >= 8):
                continue
            if any(contains_value(r.response_body, value)
                   or any(contains_value(h, value) for h in (r.response_headers or {}).values())
                   for r in requests[:k]):
                continue
            seen.add(value)
            out.append((k, loc, value))
    return out


def assess(
    correlated: list[CorrelatedValue],
    requests: list,
    requests2: list | None = None,
    comparison: dict | None = None,
) -> dict:
    """
    How far to trust an auto-correlation result before replaying it: a 0-100
    score, a label and the reasons. Replay & fix is still the final check.
    """
    from projectstack.analyzer.har_analyzer import missing_response_bodies
    from projectstack.correlator.engine import pair_requests
    from projectstack.correlator.matching import request_values

    factors: list[dict] = []

    def add(impact: str, text: str) -> None:
        factors.append({"impact": impact, "text": text})

    active = [cv for cv in correlated if "static_in_both" not in (cv.detection_pass or "")]
    switched_off = len(correlated) - len(active)
    scores = [score(cv) for cv in active]
    high = sum(s >= 75 for s in scores)
    medium = sum(50 <= s < 75 for s in scores)
    low = sum(s < 50 for s in scores)
    confirmed = sum("confirmed_dynamic" in (cv.detection_pass or "") for cv in active)

    total = 100
    if active:
        add("positive" if high else "neutral",
            f"{len(active)} correlation{'s' if len(active) != 1 else ''}: {high} high, {medium} medium, {low} low confidence")
    else:
        add("neutral", "No dynamic values found — fine for a static flow, risky for anything with a login or forms")
    if low:
        total -= min(20, 5 * low)
        add("negative", f"{low} low-confidence correlation{'s' if low != 1 else ''} — check they are really dynamic")
    if medium:
        total -= min(10, 2 * medium)

    # Values sent but never seen in a response
    untraced = _untraced_values(correlated, requests)
    changed, unknown = [], []
    if requests2 is not None:
        pairs = pair_requests(requests, requests2)
        for k, loc, value in untraced:
            j = pairs.get(k)
            if j is None:
                unknown.append((k, loc, value))
                continue
            # Identical in both recordings means static configuration — not a risk
            if value not in [v for lc, v in request_values(requests2[j]) if lc == loc]:
                changed.append((k, loc, value))
    else:
        unknown = untraced

    def examples(items):
        return ", ".join(f"{v[:24]} (#{k + 1}, {loc.split(':', 1)[0]})" for k, loc, v in items[:3])

    if changed:
        total -= min(36, 12 * len(changed))
        add("negative", f"{len(changed)} value{'s' if len(changed) != 1 else ''} changed between the recordings but "
                        f"come from no recorded response — probably generated by JavaScript: {examples(changed)}")
    if unknown:
        total -= min(24, 4 * len(unknown))
        add("negative", f"{len(unknown)} value{'s' if len(unknown) != 1 else ''} sent by requests could not be traced to "
                        f"a response: {examples(unknown)}. Fine if you typed them or they never change")
    if not untraced:
        add("positive", "Every dynamic-looking value the requests send is accounted for")

    missing = missing_response_bodies(requests)
    if missing:
        total -= min(20, 5 * len(missing))
        add("negative", f"{len(missing)} response{'s' if len(missing) != 1 else ''} saved without a body "
                        f"(#{', #'.join(str(i + 1) for i in missing[:5])}) — values inside them cannot be found")

    if requests2 is None:
        total -= 5
        add("neutral", "Not cross-checked — upload a second recording with different data to confirm what changes")
    else:
        paired = (comparison or {}).get("paired", 0)
        ratio = paired / len(requests) if requests else 1
        if ratio < 0.7:
            total -= 10
            add("negative", f"Only {paired} of {len(requests)} requests line up with the second recording — "
                            "record the same steps for a reliable comparison")
        same_tokens = sum("same_in_both" in (cv.detection_pass or "") for cv in active)
        if confirmed:
            add("positive", f"{confirmed} value{'s' if confirmed != 1 else ''} confirmed dynamic by the second recording")
        nothing_changed = not confirmed and (same_tokens + switched_off) >= 2
        if nothing_changed:
            total = min(total - 15, 70)   # the comparison proved nothing: at most Medium
            add("negative", "Nothing changed between the two recordings — was the same recording uploaded twice? "
                            "Record the journey again in a fresh browser session")
        elif same_tokens:
            total -= min(15, 5 * same_tokens)
            add("negative", f"{same_tokens} token{'s' if same_tokens != 1 else ''} had the same value in both recordings "
                            "(kept on) — if both runs shared a browser session, record the second one after logging out")
        if switched_off:
            add("neutral", f"{switched_off} value{'s' if switched_off != 1 else ''} identical in both recordings — "
                           "switched off as probably static")

    total = max(0, min(100, total))
    lbl = "High" if total >= 80 else "Medium" if total >= 55 else "Low"
    headline = {
        "High": "Auto-correlation looks complete. Confirm it with Replay & fix.",
        "Medium": "Probably usable — review the flagged items, then run Replay & fix.",
        "Low": "Likely incomplete — the script may fail. Review the items below and run Replay & fix.",
    }[lbl]
    return {
        "score": total, "label": lbl, "headline": headline, "factors": factors,
        "counts": {"correlations": len(active), "high": high, "medium": medium, "low": low,
                   "confirmed": confirmed, "switched_off": switched_off,
                   "same_tokens": sum("same_in_both" in (cv.detection_pass or "") for cv in active),
                   "untraced": len(untraced), "missing_bodies": len(missing)},
    }
